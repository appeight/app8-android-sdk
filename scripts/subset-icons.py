#!/usr/bin/env python3
"""Subset the bundled Material Symbols Rounded font to the icons the SDK maps.

The full variable font is ~15 MB (4,300 icons); the engine only draws the Material names in
engine/src/main/assets/a8/sf-to-material.json plus engine/extra-icons.txt (engine chrome and
icons hosts name in `android` overrides). This script writes:

  engine/src/main/res/font/material_symbols_rounded.ttf   the subset (FILL, opsz, wght; GRAD pinned to 0)
  engine/src/main/assets/a8/material-codepoints.json      name -> codepoint, exactly the subset

The engine draws icons by codepoint (Private Use Area), so the ligature lookups (`rlig`, which
pull in every icon through the letters a-z) are dropped. The `rclt` lookup and its
FeatureVariations record stay: they swap in the filled glyphs at FILL=1.

Upstream: github.com/google/material-design-icons @ 10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7
  variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf          (sha1 4b8517e2f5d82f107eaeaa6554ca7a95754dc02f)
  variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].codepoints

Usage (fonttools + brotli in a venv; download the upstream files outside the repo):
  python3 -m venv /tmp/venv && /tmp/venv/bin/pip install fonttools brotli
  /tmp/venv/bin/python scripts/subset-icons.py --font <upstream.ttf> --codepoints <upstream.codepoints>

To add an icon: append its Material name to engine/extra-icons.txt (or map an SF name to it in
sf-to-material.json), rerun this script, and commit the font and the codepoints file.
"""

import argparse
import io
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

UPSTREAM_SHA = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "engine"
MAPPING = ENGINE / "src/main/assets/a8/sf-to-material.json"
EXTRA = ENGINE / "extra-icons.txt"
OUT_FONT = ENGINE / "src/main/res/font/material_symbols_rounded.ttf"
OUT_CODEPOINTS = ENGINE / "src/main/assets/a8/material-codepoints.json"


def wanted_names() -> list[str]:
    mapped = json.loads(MAPPING.read_text())["symbols"].values()
    extra = [l.split("#", 1)[0].strip() for l in EXTRA.read_text().splitlines()]
    return sorted(set(mapped) | {n for n in extra if n})


def read_codepoints(path: Path) -> dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        if line.strip():
            name, cp = line.split()
            out[name] = int(cp, 16)
    return out


def build(font_path: Path, unicodes: set[int], pin_grad: bool) -> bytes:
    font = TTFont(font_path)
    options = subset.Options()
    options.layout_features = ["rclt"]  # FILL alternates; no `rlig` ligatures
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.glyph_names = False
    options.hinting = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    if pin_grad:
        font = instancer.instantiateVariableFont(font, {"GRAD": 0})
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", type=Path, required=True, help="upstream MaterialSymbolsRounded[...].ttf")
    ap.add_argument("--codepoints", type=Path, required=True, help="upstream MaterialSymbolsRounded[...].codepoints")
    ap.add_argument("--keep-grad", action="store_true", help="keep the GRAD axis (default: pinned to 0)")
    args = ap.parse_args()

    codepoints = read_codepoints(args.codepoints)
    names = wanted_names()
    missing = [n for n in names if n not in codepoints]
    if missing:
        print(f"unknown Material Symbols names: {', '.join(missing)}", file=sys.stderr)
        return 1
    table = {n: codepoints[n] for n in names}
    cmap = TTFont(args.font).getBestCmap()
    absent = [n for n, cp in table.items() if cp not in cmap]
    if absent:
        print(f"codepoints missing from the font: {', '.join(absent)}", file=sys.stderr)
        return 1

    unicodes = set(table.values())
    data = build(args.font, unicodes, pin_grad=not args.keep_grad)
    other = build(args.font, unicodes, pin_grad=args.keep_grad)
    full = args.font.stat().st_size
    label = ("keep GRAD", "GRAD pinned to 0") if args.keep_grad else ("GRAD pinned to 0", "keep GRAD")
    print(f"upstream font: {full:,} bytes ({len(cmap):,} codepoints)")
    print(f"subset ({label[0]}): {len(data):,} bytes   [{label[1]}: {len(other):,} bytes]")
    print(f"icons: {len(table)} names, {len(unicodes)} codepoints")

    OUT_FONT.write_bytes(data)
    OUT_CODEPOINTS.write_text(json.dumps({
        "version": 1,
        "comment": "Generated by scripts/subset-icons.py: Material Symbols name -> codepoint (hex) for every "
                   "glyph in res/font/material_symbols_rounded.ttf. Do not edit; add names to engine/extra-icons.txt.",
        "upstream": UPSTREAM_SHA,
        "codepoints": {n: f"{cp:x}" for n, cp in table.items()},
    }, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
